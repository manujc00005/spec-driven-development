#!/usr/bin/env node
/**
 * link-workspace.mjs — tells each child project it belongs to this workspace.
 *
 * Why: workspace onboarding builds `.sdd-workspace/` but writes nothing inside child
 * projects. The result is a governance layer only visible from the root — and most
 * sessions open inside a repo. This inserts a delimited block at the top of each
 * project's instruction file saying which workspace it belongs to, what to read before
 * proposing anything, and the cross-repo rules.
 *
 * Idempotent by delimiters: re-run after adding a repo or changing the text — it
 * replaces its own block, never duplicates, never touches anything outside it.
 * The text is edited HERE, never in the repos.
 *
 * Usage:  node .sdd-workspace/scripts/link-workspace.mjs [--check]
 *         --check  don't write; exit 1 if any project is unlinked. For hooks/CI.
 *
 * Projects: `.sdd-workspace/workspace.json` ({"projects":[...]}) if present; otherwise
 * auto-detect top-level dirs with a manifest marker or a specs/ directory.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = process.env.SDD_WS_ROOT || join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const WS = basename(ROOT);
const MARKERS = ["package.json", "pyproject.toml", "pom.xml", "go.mod", "Cargo.toml", "specs"];
const TARGETS = ["CLAUDE.md", "specs/CLAUDE-SDD.md", "AGENTS.md", "README.md"];
const START = "<!-- SDD-WORKSPACE:START -->";
const END = "<!-- SDD-WORKSPACE:END -->";

function detectProjects() {
  const cfg = join(ROOT, ".sdd-workspace", "workspace.json");
  if (existsSync(cfg)) {
    const j = JSON.parse(readFileSync(cfg, "utf8"));
    if (Array.isArray(j.projects) && j.projects.length) return j.projects;
  }
  return readdirSync(ROOT, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith(".") && e.name !== "docs" &&
      MARKERS.some((m) => existsSync(join(ROOT, e.name, m))))
    .map((e) => e.name);
}

const block = () => `${START}
> ### This project lives in the \`${WS}\` workspace
>
> It is not an isolated repository: it shares contracts and decisions with its sibling
> projects. **Before proposing or touching anything**, read at the workspace root (\`../\`):
>
> | File | What for |
> |---|---|
> | \`.sdd-workspace/BOARD.md\` | What is active across **all** projects. Generated — never edited |
> | \`.sdd-workspace/HOW-TO-WORK.md\` | How work happens here, incl. the cross-repo protocol |
> | \`.sdd-workspace/SHARED_DECISIONS.md\` | **Binding** decisions between projects |
> | \`.sdd-workspace/INTEGRATION_CONTRACTS.md\` | The contracts this repo consumes or publishes |
> | \`CLAUDE.md\` (root) | The rules every session must follow |
>
> **Three rules that hold no matter where the session opens:**
>
> 1. **One unblocked active work item across the whole workspace**, not one per repo. Check with
>    \`node ../.sdd-workspace/scripts/board.mjs --list\` before starting anything.
> 2. **A shared contract changes in the repo that owns it, and is documented before** any
>    consumer implements against it. Never from a consumer.
> 3. **If the work leaves this repo, stop.** Discovering that another project needs touching is
>    a reason to record it, not to continue. Only a \`BLOCKER\` interrupts.
>
> *Block generated by \`.sdd-workspace/scripts/link-workspace.mjs\`. Do not edit by hand: it is
> regenerated. To change the text, change it in the script.*
${END}`;

function insert(text, b) {
  const i = text.indexOf(START);
  if (i !== -1) {
    const j = text.indexOf(END);
    if (j === -1) throw new Error("open block without END marker");
    return text.slice(0, i) + b + text.slice(j + END.length);
  }
  const lines = text.split("\n");
  const h1 = lines.findIndex((l) => /^#\s+\S/.test(l));
  if (h1 === -1) return b + "\n\n" + text;
  return lines.slice(0, h1 + 1).join("\n") + "\n\n" + b + "\n" + lines.slice(h1 + 1).join("\n");
}

const check = process.argv.includes("--check");
const b = block();
const out = [];
let failing = 0;

for (const p of detectProjects()) {
  const dir = join(ROOT, p);
  if (!existsSync(dir)) continue;
  const rel = TARGETS.find((t) => existsSync(join(dir, t)));
  if (!rel) { out.push(`  · ${p} — no instruction file (${TARGETS.join(", ")})`); continue; }
  const file = join(dir, rel);
  const current = readFileSync(file, "utf8");
  const next = insert(current, b);
  if (next === current) { out.push(`  ✓ ${p}/${rel} — up to date`); continue; }
  if (check) { failing++; out.push(`  ✗ ${p}/${rel} — ${current.includes(START) ? "outdated" : "NOT LINKED"}`); continue; }
  writeFileSync(file, next, "utf8");
  out.push(`  ✓ ${p}/${rel} — ${current.includes(START) ? "updated" : "linked"}`);
}
process.stdout.write(out.join("\n") + "\n");
process.exit(check && failing ? 1 : 0);
